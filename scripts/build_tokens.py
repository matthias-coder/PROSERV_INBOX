#!/usr/bin/env python3
"""Generate board/tokens.css from design/titania/tokens.json (TITANIA Design System).

Light values go on :root. Dark values are written twice, as the claude.ai viewer needs:
once for prefers-color-scheme (unless the viewer forces light) and once for data-theme="dark".
Run from the repository root:  python3 scripts/build_tokens.py
"""
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "design" / "titania" / "tokens.json"
OUT = ROOT / "board" / "tokens.css"

ALIAS = re.compile(r"^\{([A-Za-z0-9_.-]+)\}$")


def css_value(value):
    m = ALIAS.match(str(value))
    return f"var(--{m.group(1)})" if m else str(value)


def main():
    tokens = json.loads(SRC.read_text(encoding="utf-8"))
    themes = [t["id"] for t in tokens["color"]["themes"]]
    first = themes[0]
    light, dark = [], []
    for tok in tokens["color"]["tokens"]:
        value = tok["value"]
        if isinstance(value, dict):
            light.append((tok["name"], css_value(value.get(first))))
            if "dark" in value and value["dark"] != value.get(first):
                dark.append((tok["name"], css_value(value["dark"])))
        else:
            light.append((tok["name"], css_value(value)))
    plain = []
    for family, body in tokens.items():
        if family in ("color", "type") or not isinstance(body, dict) or "tokens" not in body:
            continue
        for tok in body["tokens"]:
            plain.append((tok["name"], css_value(tok["value"])))
    for name, stack in tokens["type"]["families"].items():
        plain.append((f"font-{name}", stack))

    def block(pairs, indent="  "):
        return "\n".join(f"{indent}--{n}: {v};" for n, v in pairs)

    meta = tokens.get("meta", {})
    css = (
        f"/* Generated by scripts/build_tokens.py from design/titania/tokens.json "
        f"(TITANIA Design System, {meta.get('ref', 'unknown ref')}, synced {meta.get('synced', '?')}). Do not edit. */\n"
        f":root {{\n{block(light)}\n{block(plain)}\n}}\n"
        f"@media (prefers-color-scheme: dark) {{\n  :root:not([data-theme=\"light\"]) {{\n"
        f"{block(dark, '    ')}\n    color-scheme: dark;\n  }}\n}}\n"
        f":root[data-theme=\"dark\"] {{\n{block(dark)}\n  color-scheme: dark;\n}}\n"
    )
    OUT.write_text(css, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(light)} colours ({len(dark)} with a dark value), {len(plain)} other tokens")


if __name__ == "__main__":
    main()
